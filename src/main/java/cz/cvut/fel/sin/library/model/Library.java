package cz.cvut.fel.sin.library.model;

import jakarta.persistence.*;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.util.ArrayList;
import java.util.List;

/**
 * A library (a building/institution) that owns copies of books.
 * <p>
 * DB table: {@code library}. One library can own many book titles,
 * each through one {@link Ownership} row (which also stores the number of copies).
 */
@Entity // this class is a table
@Table(name = "library") // DB: table name "library"
@Getter @Setter // Lombok: generates getters + setters for all fields
@NoArgsConstructor // Lombok: empty constructor, JPA needs it to create objects from DB rows
public class Library {

    /** Surrogate primary key, generated by the database. */
    @Id // DB: PRIMARY KEY
    @GeneratedValue(strategy = GenerationType.IDENTITY) // DB generates it (surrogate key) -> auto-increment / IDENTITY column
    @Column(name = "library_id") // DB: column name "library_id" (not "id")
    private Long id;

    /** Name of the library, required. */
    @NotBlank // Bean Validation: not null, not empty, not just spaces --> IN JAVA
    @Column(nullable = false) // DB constraint: NOT NULL --> IN DB
    private String name;

    /** Address of the library, stored as columns of this table (no own table). */
    @Valid // validate the fields inside Address too (rn nothing bcs Adress has no rules)
    @Embedded // columns street, city, zip, country go into the "library" table
    private Address address;

    /** Book titles this library owns (with number of copies). */
    // Library "1" -- "0..*" Ownership
    // cascade = ALL: save/delete of Library is also done on its Ownerships
    // orphanRemoval = true: Ownership removed from this list -> DELETE its row from DB
    @OneToMany(mappedBy = "library", cascade = CascadeType.ALL, orphanRemoval = true)
    private List<Ownership> ownerships = new ArrayList<>();

    /**
     * Two libraries are equal when they have the same database id.
     *
     * @param o the other object
     * @return true if it is the same library (same id)
     */
    // equals/hashCode BY ID: needed once entities sit in Sets (e.g. Book.authors)
    // if 2 have the same ID, they are the same entity (even if other fields differ)
    @Override
    public boolean equals(Object o) {
        // same object in memory -> obviously equal
        if (this == o) return true;
        // other object is not a Library (or is null) -> not equal
        // (also casts it into variable "other" so we can use it below)
        if (!(o instanceof Library other)) return false;
        // equal only if both have the same id
        // id != null: a new, not-yet-saved library has no id -> equal only to itself (checked above)
        return id != null && id.equals(other.id);
    }

    /**
     * Constant hash code, so it does not change when the DB assigns the id after save.
     *
     * @return hash code of the class
     */
    // if 2 objects are equal, they must have the same hashCode
    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    // No add/remove helpers here: ownerships are managed by Ownership itself
    //   create: new Ownership(library, book, copies)  -> adds itself to both lists
    //   delete: ownership.remove()                    -> removes itself from both lists
}

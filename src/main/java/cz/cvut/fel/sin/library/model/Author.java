package cz.cvut.fel.sin.library.model;

import jakarta.persistence.*;
import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.NotBlank;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.util.HashSet;
import java.util.Set;

/**
 * An author who writes books and has contracts with publishers.
 * <p>
 * DB table: {@code author}.
 * Author N:M {@link Book} via join table {@code writes} (owned by Book),
 * Author N:M {@link Publisher} via join table {@code contract} (owned by Author).
 */
@Entity // this class is a table
@Table(name = "author") // DB: table name "author"
@Getter @Setter // Lombok: getters + setters
@NoArgsConstructor // Lombok: empty constructor, JPA needs it
public class Author {

    /** Surrogate primary key, generated by the database. */
    @Id // DB: PRIMARY KEY
    @GeneratedValue(strategy = GenerationType.IDENTITY) // DB: auto-increment
    @Column(name = "author_id") // DB: column name "author_id"
    private Long id;

    /** First name, required. */
    @NotBlank // Java: not null / empty / spaces
    @Column(name = "first_name", nullable = false) // DB: column "first_name" NOT NULL
    private String firstName;

    /** Last name, required. */
    @NotBlank // Java: not null / empty / spaces
    @Column(name = "last_name", nullable = false) // DB: column "last_name" NOT NULL
    private String lastName;

    /** E-mail address (optional), must be a valid e-mail if filled. */
    @Email // Java: must look like an e-mail (null is allowed)
    private String email; // DB: column "email", can be NULL

    /** Publishers this author has a contract with. */
    // Author "0..*" -- "0..*" Publisher  (N:M)
    // OWNING side of "contract": this field defines the join table
    //   (the other side, Publisher.authors, has mappedBy = "publishers")
    // fetch: @ManyToMany is LAZY by default
    // NO cascade: deleting an author must not delete publishers (they are shared)
    @ManyToMany
    // @JoinTable: DB creates table "contract"(author_id, publisher_id), PK = both columns
    @JoinTable(
            name = "contract",
            joinColumns = @JoinColumn(name = "author_id"),          // FK -> author(author_id)   (this side)
            inverseJoinColumns = @JoinColumn(name = "publisher_id") // FK -> publisher(publisher_id) (other side)
    )
    private Set<Publisher> publishers = new HashSet<>(); // Best to use HashSet for N:M, because it prevents duplicates and is faster than List for contains() checks.

    /** Books this author wrote. */
    // Author "0..*" -- "1..*" Book  (N:M)
    // mappedBy = "authors": Book.authors is the OWNING side (defines the "writes" table),
    //   this set is only a mirror -> DB: nothing extra here, read from writes table
    @ManyToMany(mappedBy = "authors")
    private Set<Book> books = new HashSet<>();

    // Helper methods: change BOTH sides of the N:M at once (this.publishers + publisher.authors),
    // so Java objects match the DB right away. YOU call these in the Service layer.

    /**
     * Creates a contract between this author and a publisher (both sides).
     *
     * @param publisher the publisher to sign a contract with
     */
    public void addPublisher(Publisher publisher) {
        publishers.add(publisher);          // owning side -> DB: INSERT INTO contract
        publisher.getAuthors().add(this);   // mirror side (Java only)
    }

    /**
     * Ends the contract between this author and a publisher (both sides).
     *
     * @param publisher the publisher to end the contract with
     */
    public void removePublisher(Publisher publisher) {
        publishers.remove(publisher);          // owning side -> DB: DELETE FROM contract
        publisher.getAuthors().remove(this);   // mirror side (Java only)
    }

    /**
     * Two authors are equal when they have the same database id.
     *
     * @param o the other object
     * @return true if it is the same author (same id)
     */
    @Override
    public boolean equals(Object o) {
        if (this == o) return true; // same object in memory
        if (!(o instanceof Author other)) return false; // not an Author (or null)
        return id != null && id.equals(other.id); // same id = same row (unsaved -> no id -> not equal)
    }

    /**
     * Constant hash code, so it does not change when the DB assigns the id after save.
     *
     * @return hash code of the class
     */
    @Override
    public int hashCode() {
        return getClass().hashCode();
    }
}

package cz.cvut.fel.sin.library.model;

import jakarta.persistence.*;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotNull;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * "This library owns this book title, in N copies."
 * <p>
 * Conceptually Library N:M Book, but because the relationship has its own attribute
 * ({@code copies}) it is a separate entity: {@code Library 1 -- N Ownership N -- 1 Book}.
 * <p>
 * DB table: {@code ownership(id, library_id, book_id, copies)},
 * the pair (library_id, book_id) is unique.
 */
@Entity // this class is a table
@Table(
        name = "ownership", // DB: table name "ownership"
        // DB: UNIQUE (library_id, book_id) -> each library + book pair only once
        uniqueConstraints = @UniqueConstraint(columnNames = {"library_id", "book_id"})
)
@Getter @Setter // Lombok: getters + setters
@NoArgsConstructor // Lombok: empty constructor, required by JPA
public class Ownership {

    /** Surrogate primary key, generated by the database. */
    @Id // DB: PRIMARY KEY
    @GeneratedValue(strategy = GenerationType.IDENTITY) // DB: auto-increment
    private Long id;

    /** The library that owns the book. Required. */
    // Ownership "0..*" -- "1" Library
    // owning side: this table holds the FK library_id
    @NotNull // Java: must be set before save
    // @ManyToOne: many ownerships -> one library
    //   fetch = LAZY: library is loaded from DB only when you call getLibrary()
    //   optional = false: JPA knows it's always present (can use INNER JOIN)
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    // @JoinColumn: DB column "library_id" = FOREIGN KEY -> library(library_id)
    //   nullable = false -> NOT NULL
    @JoinColumn(name = "library_id", nullable = false)
    private Library library;

    /** The book title that is owned. Required. */
    // Ownership "0..*" -- "1" Book
    // owning side: this table holds the FK book_id
    @NotNull // Java: must be set before save
    @ManyToOne(fetch = FetchType.LAZY, optional = false) // many ownerships -> one book, loaded lazily
    @JoinColumn(name = "book_id", nullable = false) // DB: FK book_id -> book(isbn), NOT NULL (column holds the ISBN)
    private Book book;

    /** How many identical copies this library has, 1 to 5. */
    // how many copies of this book this library has (max 5 identical books)
    @Min(1) @Max(5) // Java: value must be between 1 and 5
    @Column(nullable = false) // DB: NOT NULL
    private int copies;

    /**
     * Creates an ownership of a book by a library and links it on BOTH sides
     * (into {@code library.ownerships} and {@code book.ownerships}).
     * <p>
     * Usage: {@code new Ownership(library, book, 3); libraryRepository.save(library);}
     * (cascade on Library saves the ownership too).
     *
     * @param library the owning library
     * @param book    the owned book title
     * @param copies  number of copies (1-5)
     */
    // THIS one YOU call in the Service layer to create an ownership
    public Ownership(Library library, Book book, int copies) {
        this.library = library;               // ownership -> library (FK library_id in the DB)
        this.book = book;                     // ownership -> book    (FK book_id in the DB)
        this.copies = copies;
        library.getOwnerships().add(this);    // library knows it (Java list only)
        book.getOwnerships().add(this);       // book knows it too (Java list only)
    }

    /**
     * Removes this ownership from its library and its book.
     * <p>
     * No repository delete needed: once it is in neither list, orphanRemoval
     * deletes the row from the DB at the end of the transaction.
     * Usage: {@code ownership.remove();}
     */
    // THIS one YOU call in the Service layer to delete an ownership (instead of ownershipRepository.delete())
    public void remove() {
        library.getOwnerships().remove(this); // library forgets it (orphanRemoval -> DELETE)
        book.getOwnerships().remove(this);    // book forgets it too, so book's cascade won't keep it alive
        // library/book are NOT set to null: the row is being deleted anyway, and null would break NOT NULL
    }

    /**
     * Two ownerships are equal when they have the same database id.
     *
     * @param o the other object
     * @return true if it is the same ownership (same id)
     */
    @Override
    public boolean equals(Object o) {
        if (this == o) return true; // same object in memory
        if (!(o instanceof Ownership other)) return false; // not an Ownership (or null)
        return id != null && id.equals(other.id); // same id = same row in DB (unsaved -> no id -> not equal)
    }

    /**
     * Constant hash code, so it does not change when the DB assigns the id after save.
     *
     * @return hash code of the class
     */
    @Override
    public int hashCode() {
        return getClass().hashCode();
    }
}

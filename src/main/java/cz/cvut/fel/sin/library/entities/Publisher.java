package cz.cvut.fel.sin.library.entities;

import jakarta.persistence.*;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

/**
 * A publishing house that publishes books and has contracts with authors.
 * <p>
 * DB table: {@code publisher}. One publisher publishes many {@link Book}s (1:N)
 * and has contracts with many {@link Author}s (N:M, join table {@code contract}).
 */
@Entity // this class is a table
@Table(name = "publisher") // DB: table name "publisher"
@Getter @Setter // Lombok: getters + setters
@NoArgsConstructor // Lombok: empty constructor, JPA needs it
public class Publisher {

    /** Surrogate primary key, generated by the database. */
    @Id // DB: PRIMARY KEY
    @GeneratedValue(strategy = GenerationType.IDENTITY) // DB: auto-increment
    @Column(name = "publisher_id") // DB: column name "publisher_id"
    private Long id;

    /** Name of the publisher, required. */
    @NotBlank // Java: not null, not empty, not just spaces
    @Column(nullable = false) // DB: NOT NULL
    private String name;

    /** Address of the publisher, stored as columns of this table (no own table). */
    @Valid // validate the fields inside Address too
    @Embedded // DB: columns street, city, zip, country go into the "publisher" table
    private Address address;

    /** Books published by this publisher. */
    // Publisher "1" -- "0..*" Book
    // mappedBy = "publisher": the FK (publisher_id) lives in Book, this list is only a mirror
    //   -> DB: NO column in "publisher" table for this, it's read from book.publisher_id
    // NO cascade: deleting a publisher must not delete its books
    //   (DB will refuse deleting a publisher that still has books -> FK error, which is what we want)
    @OneToMany(mappedBy = "publisher")
    private List<Book> books = new ArrayList<>();

    /** Authors that have a contract with this publisher. */
    // Publisher "0..*" -- "0..*" Author  (N:M, join table "contract")
    // mappedBy = "publishers": Author.publishers is the OWNING side (it defines the join table),
    //   this set is only a mirror -> DB: nothing extra here, read from contract table
    // fetch: @ManyToMany is LAZY by default (authors loaded only when you call getAuthors())
    @ManyToMany(mappedBy = "publishers")
    private Set<Author> authors = new HashSet<>();

    /**
     * Two publishers are equal when they have the same database id.
     *
     * @param o the other object
     * @return true if it is the same publisher (same id)
     */
    @Override
    public boolean equals(Object o) {
        if (this == o) return true; // same object in memory
        if (!(o instanceof Publisher other)) return false; // not a Publisher (or null)
        return id != null && id.equals(other.id); // same id = same row (unsaved -> no id -> not equal)
    }

    /**
     * Constant hash code, so it does not change when the DB assigns the id after save.
     *
     * @return hash code of the class
     */
    @Override
    public int hashCode() {
        return getClass().hashCode();
    }
}

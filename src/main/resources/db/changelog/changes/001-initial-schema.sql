--liquibase formatted sql

-- 001: initial schema = all tables of exercise 2 (matches the JPA entities).
-- Each "--changeset author:id" block is one change, Liquibase runs it only once per DB.
-- "--rollback" = how to undo the change (used only if you run a Liquibase rollback manually).
-- SQL is kept standard so it works on PostgreSQL (app) and H2 (tests).

--changeset miscisam:001-library
-- Library: surrogate key, address embedded as columns
CREATE TABLE library (
    library_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    street     VARCHAR(255),
    city       VARCHAR(255),
    zip        VARCHAR(255),
    country    VARCHAR(255)
);
--rollback DROP TABLE library;

--changeset miscisam:001-publisher
-- Publisher: surrogate key, address embedded as columns
CREATE TABLE publisher (
    publisher_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL,
    street       VARCHAR(255),
    city         VARCHAR(255),
    zip          VARCHAR(255),
    country      VARCHAR(255)
);
--rollback DROP TABLE publisher;

--changeset miscisam:001-author
CREATE TABLE author (
    author_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(255) NOT NULL,
    last_name  VARCHAR(255) NOT NULL,
    email      VARCHAR(255)
);
--rollback DROP TABLE author;

--changeset miscisam:001-book
-- Book: ISBN = natural primary key, genre = enum Genre stored as text, every book has a publisher (1:N)
CREATE TABLE book (
    isbn             VARCHAR(17)  PRIMARY KEY,
    title            VARCHAR(255) NOT NULL,
    publication_date DATE,
    genre            VARCHAR(255),
    publisher_id     BIGINT       NOT NULL,
    CONSTRAINT ck_book_genre     CHECK (genre IN ('NOVEL', 'POETRY', 'SCIENCE', 'CHILDREN')),
    CONSTRAINT fk_book_publisher FOREIGN KEY (publisher_id) REFERENCES publisher (publisher_id)
);
--rollback DROP TABLE book;

--changeset miscisam:001-ownership
-- Ownership: Library N:M Book with attribute copies, each library + book pair only once
CREATE TABLE ownership (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    library_id BIGINT      NOT NULL,
    book_id    VARCHAR(17) NOT NULL,
    copies     INTEGER     NOT NULL,
    CONSTRAINT ck_ownership_copies  CHECK (copies BETWEEN 1 AND 5),
    CONSTRAINT uq_ownership         UNIQUE (library_id, book_id),
    CONSTRAINT fk_ownership_library FOREIGN KEY (library_id) REFERENCES library (library_id),
    CONSTRAINT fk_ownership_book    FOREIGN KEY (book_id)    REFERENCES book (isbn)
);
--rollback DROP TABLE ownership;

--changeset miscisam:001-writes
-- writes: join table Book N:M Author
CREATE TABLE writes (
    isbn      VARCHAR(17) NOT NULL,
    author_id BIGINT      NOT NULL,
    CONSTRAINT pk_writes        PRIMARY KEY (isbn, author_id),
    CONSTRAINT fk_writes_book   FOREIGN KEY (isbn)      REFERENCES book (isbn),
    CONSTRAINT fk_writes_author FOREIGN KEY (author_id) REFERENCES author (author_id)
);
--rollback DROP TABLE writes;

--changeset miscisam:001-contract
-- contract: join table Author N:M Publisher
CREATE TABLE contract (
    author_id    BIGINT NOT NULL,
    publisher_id BIGINT NOT NULL,
    CONSTRAINT pk_contract           PRIMARY KEY (author_id, publisher_id),
    CONSTRAINT fk_contract_author    FOREIGN KEY (author_id)    REFERENCES author (author_id),
    CONSTRAINT fk_contract_publisher FOREIGN KEY (publisher_id) REFERENCES publisher (publisher_id)
);
--rollback DROP TABLE contract;
